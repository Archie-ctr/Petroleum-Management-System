// Get database size
$db_size_sql = "SELECT 
    table_schema as 'Database',
    SUM(data_length + index_length) / 1024 / 1024 as 'Size_MB'
    FROM information_schema.TABLES 
    WHERE table_schema = DATABASE()
    GROUP BY table_schema";
$db_size_result = $conn->query($db_size_sql);
$db_size = $db_size_result->fetch_assoc();
$database_size = round($db_size['Size_MB'], 2);

// Get total tables count
$tables_sql = "SELECT COUNT(*) as total_tables 
               FROM information_schema.TABLES 
               WHERE table_schema = DATABASE()";
$tables_result = $conn->query($tables_sql);
$total_tables = $tables_result->fetch_assoc()['total_tables'];

// Get backup directory
$backup_dir = '../database/backups/';
if (!file_exists($backup_dir)) {
    mkdir($backup_dir, 0777, true);
}

// Handle backup creation
if (isset($_POST['create_backup'])) {
    $backup_name = 'backup_' . date('Y-m-d_H-i-s') . '.sql';
    $backup_file = $backup_dir . $backup_name;
    
    // Get all tables
    $tables = [];
    $result = $conn->query('SHOW TABLES');
    while ($row = $result->fetch_row()) {
        $tables[] = $row[0];
    }
    
    // Create backup file
    $output = "-- God Willing Business Center Database Backup\n";
    $output .= "-- Backup Date: " . date('Y-m-d H:i:s') . "\n";
    $output .= "-- Database: if0_40669260_godwilling_db\n";
    $output .= "-- Generated by: " . $_SESSION['full_name'] . "\n\n";
    
    foreach ($tables as $table) {
        // Add table structure
        $result = $conn->query("SHOW CREATE TABLE `$table`");
        $row = $result->fetch_row();
        $output .= "\n-- Table structure for table `$table`\n";
        $output .= "DROP TABLE IF EXISTS `$table`;\n";
        $output .= $row[1] . ";\n\n";
        
        // Add table data
        $result = $conn->query("SELECT * FROM `$table`");
        if ($result->num_rows > 0) {
            $output .= "-- Dumping data for table `$table`\n";
            $output .= "INSERT INTO `$table` VALUES\n";
            
            $rows = [];
            while ($row = $result->fetch_row()) {
                $values = array_map(function($value) use ($conn) {
                    if ($value === null) return 'NULL';
                    return "'" . $conn->real_escape_string($value) . "'";
                }, $row);
                $rows[] = "(" . implode(', ', $values) . ")";
            }
            $output .= implode(",\n", $rows) . ";\n\n";
        }
    }
    
    // Save to file
    if (file_put_contents($backup_file, $output)) {
        $success_message = "Backup created successfully: " . $backup_name;
    } else {
        $error_message = "Failed to create backup file";
    }
}

// Handle backup restoration
if (isset($_POST['restore_backup'])) {
    $backup_file = $_POST['backup_file'];
    $full_path = $backup_dir . $backup_file;
    
    if (file_exists($full_path)) {
        // Read backup file
        $sql = file_get_contents($full_path);
        
        // Temporarily disable foreign key checks
        $conn->query('SET FOREIGN_KEY_CHECKS = 0');
        
        // Split SQL by semicolon
        $queries = explode(';', $sql);
        
        foreach ($queries as $query) {
            $query = trim($query);
            if (!empty($query)) {
                if (!$conn->query($query)) {
                    $error_message = "Error executing query: " . $conn->error;
                    break;
                }
            }
        }
        
        // Re-enable foreign key checks
        $conn->query('SET FOREIGN_KEY_CHECKS = 1');
        
        $success_message = "Database restored successfully from: " . $backup_file;
    } else {
        $error_message = "Backup file not found";
    }
}

// Handle backup deletion
if (isset($_GET['delete_backup'])) {
    $backup_file = $backup_dir . $_GET['delete_backup'];
    if (file_exists($backup_file) && unlink($backup_file)) {
        $success_message = "Backup file deleted successfully";
    } else {
        $error_message = "Failed to delete backup file";
    }
    header('Location: backup_restore.php');
    exit();
}

// Handle database optimization
if (isset($_POST['optimize_database'])) {
    $result = $conn->query('SHOW TABLES');
    $tables_optimized = 0;
    
    while ($row = $result->fetch_row()) {
        $table = $row[0];
        $conn->query("OPTIMIZE TABLE `$table`");
        $tables_optimized++;
    }
    
    $success_message = "Database optimized successfully. $tables_optimized tables optimized.";
}

// Get all backup files
$backup_files = [];
if (is_dir($backup_dir)) {
    $files = scandir($backup_dir);
    foreach ($files as $file) {
        if ($file != '.' && $file != '..' && pathinfo($file, PATHINFO_EXTENSION) == 'sql') {
            $file_path = $backup_dir . $file;
            $backup_files[] = [
                'name' => $file,
                'size' => round(filesize($file_path) / 1024, 2), // KB
                'modified' => date('Y-m-d H:i:s', filemtime($file_path)),
                'age' => floor((time() - filemtime($file_path)) / (60 * 60 * 24)) // Days
            ];
        }
    }
    
    // Sort by modification time (newest first)
    usort($backup_files, function($a, $b) {
        return strtotime($b['modified']) - strtotime($a['modified']);
    });
}

